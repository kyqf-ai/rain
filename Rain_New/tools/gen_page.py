#!/usr/bin/env python3
"""Embed web/index.html into src/web_page.c (run after editing the page)."""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = open(os.path.join(root, "web", "index.html"), "rb").read()
lines = ["/* generated by tools/gen_page.py from web/index.html - do not edit */",
         '#include "web.h"', "const unsigned char web_index_html[] = {"]
for i in range(0, len(data), 24):
    lines.append("  " + ",".join("0x%02x" % b for b in data[i:i + 24]) + ",")
lines += ["  0x00", "};", "const unsigned int web_index_html_len = %d;" % len(data), ""]
open(os.path.join(root, "src", "web_page.c"), "w").write("\n".join(lines))
print("web_page.c: %d bytes embedded" % len(data))
